#!/usr/bin/env bash
#
# Generate a .env for an additional ACE instance on this host.
#
# Writes to stdout so it stays side-effect free and re-runnable:
#
#   cd /opt/ace2
#   bin/generate-instance-env.sh ace2 100 > .env
#
# The offset is added to each of the five fixed host ports. It exists as a script argument
# rather than a compose variable because compose ${} interpolation cannot do arithmetic, so the
# ports have to be computed before the compose file is read.
#
# Everything else -- container names, the network, all ten named volumes -- is namespaced by the
# compose project name and needs no per-port bookkeeping. See docs/MULTI_INSTANCE.md.
#

set -u

usage() {
    echo "usage: $0 <instance-name> <port-offset>" >&2
    echo >&2
    echo "  instance-name  lowercase [a-z0-9][a-z0-9_-]* -- becomes the compose project name," >&2
    echo "                 and so the prefix on every container, volume and network" >&2
    echo "  port-offset    a positive multiple of 100 added to each fixed host port" >&2
    echo >&2
    echo "example: $0 ace2 100 > .env" >&2
    exit 2
}

[ $# -eq 2 ] || usage

INSTANCE="$1"
OFFSET="$2"

# the name becomes a docker volume name and a compose project name. compose lowercases the
# project name and strips anything outside [a-z0-9_-], so anything else silently becomes a
# different name than the one the phishkit/js-deobfuscator managers are handed.
if ! printf '%s' "$INSTANCE" | grep -qE '^[a-z0-9][a-z0-9_-]*$'; then
    echo "error: instance name '$INSTANCE' must match [a-z0-9][a-z0-9_-]*" >&2
    exit 1
fi

if ! printf '%s' "$OFFSET" | grep -qE '^[0-9]+$'; then
    echo "error: port offset '$OFFSET' must be a positive integer" >&2
    exit 1
fi

# a multiple of 100 keeps the GUI port (5000+offset) clear of the dev container's default
# 5001 -- an offset of 1 would collide the two instances' ports with each other.
if [ "$OFFSET" -le 0 ] || [ $(( OFFSET % 100 )) -ne 0 ]; then
    echo "error: port offset must be a positive multiple of 100 (got $OFFSET)" >&2
    exit 1
fi

# the largest base port is fluent-bit's 24224
if [ $(( 24224 + OFFSET )) -ge 65536 ]; then
    echo "error: port offset $OFFSET pushes a port past 65535" >&2
    exit 1
fi

PORT_FLUENT_BIT=$(( 24224 + OFFSET ))
PORT_HTTP=$(( 8443 + OFFSET ))
PORT_HTTP_EXTERNAL=$(( 9443 + OFFSET ))
PORT_GUI=$(( 5000 + OFFSET ))
PORT_DEV_GUI=$(( 5001 + OFFSET ))

# warn (do not fail) about ports already in use -- the other stack may simply be running
if command -v ss >/dev/null 2>&1; then
    LISTENING="$(ss -ltnH 2>/dev/null | awk '{print $4}')"
    for p in "$PORT_FLUENT_BIT" "$PORT_HTTP" "$PORT_HTTP_EXTERNAL" "$PORT_GUI" "$PORT_DEV_GUI"; do
        if printf '%s\n' "$LISTENING" | grep -qE "[:.]${p}\$"; then
            echo "warning: port ${p} is already in use on this host" >&2
        fi
    done
else
    echo "notice: ss not found, skipping the port-in-use check" >&2
fi

cat <<EOF
#
# ACE instance '${INSTANCE}' (port offset ${OFFSET})
#
# Generated by bin/generate-instance-env.sh. See docs/MULTI_INSTANCE.md.
#

# the compose project name. prefixes every container, the network and all ten named volumes.
# do NOT also set COMPOSE_PROJECT_NAME -- it overrides the top-level name: in
# docker-compose.yml and would desynchronize the project from the volume names handed to the
# phishkit and js-deobfuscator managers.
ACE_INSTANCE=${INSTANCE}

# what this instance calls itself in the GUI
ACE_INSTANCE_NAME=${INSTANCE}

# host interface every published port binds to. set to 0.0.0.0 to reach this instance from
# another machine.
ACE_BIND_ADDRESS=127.0.0.1

# the fixed host ports. everything else (mysql, redis, rabbitmq, qdrant, the network semaphore)
# is published on an ephemeral port -- find it with \`docker compose port ace-db 3306\`.
ACE_PORT_FLUENT_BIT=${PORT_FLUENT_BIT}
ACE_PORT_HTTP=${PORT_HTTP}
ACE_PORT_HTTP_EXTERNAL=${PORT_HTTP_EXTERNAL}
ACE_PORT_GUI=${PORT_GUI}
ACE_PORT_DEV_GUI=${PORT_DEV_GUI}

# permalinks the GUI builds must point at this instance's GUI port
ACE_GUI_BASE_URI=https://localhost:${PORT_GUI}/ACE

# per-instance image tags, so that a \`docker compose build\` here does not retag the images
# another instance recreates from. drop these if every checkout is on the same revision and you
# would rather share one set of images.
ACE3_IMAGE_URL=ace3:${INSTANCE}
ACE3_PHISHKIT_IMAGE_URL=phishkit:${INSTANCE}
ACE3_PHISHKIT_MANAGER_IMAGE_URL=phishkit-manager:${INSTANCE}
ACE3_JS_DEOBFUSCATOR_IMAGE_URL=js-deobfuscator:${INSTANCE}
ACE3_JS_DEOBFUSCATOR_MANAGER_IMAGE_URL=js-deobfuscator-manager:${INSTANCE}
EOF
